func TestCronNext(t *testing.T) {
	rome, err := time.LoadLocation("Europe/Rome")
	if err != nil {
		t.Skip("no time zone data:", err)
	}
	at := func(s string, loc *time.Location) time.Time {
		v, err := time.ParseInLocation("2006-01-02 15:04", s, loc)
		if err != nil {
			t.Fatal(err)
		}
		return v
	}
	for _, c := range []struct{ spec, after, want string }{
		{"* * * * *", "2026-10-30 18:42", "2026-10-30 18:43"},
		{"*/5 * * * *", "2026-10-30 18:42", "2026-10-30 18:45"},
		{"*/5 * * * *", "2026-10-30 18:45", "2026-10-30 18:50"},
		{"0 3 * * *", "2026-10-30 18:42", "2026-10-31 03:00"},
		{"30 2 1 * *", "2026-10-30 18:42", "2026-11-01 02:30"},
		{"0 9 * * mon-fri", "2026-10-30 18:42", "2026-11-02 09:00"}, // a Friday evening
		{"0 9 * * 7", "2026-10-30 18:42", "2026-11-01 09:00"},       // 7 is Sunday too
		{"0 9 * * 5-7", "2026-10-31 10:00", "2026-11-01 09:00"},
		{"0 0 1 jan *", "2026-10-30 18:42", "2027-01-01 00:00"},
		{"15,45 8-10/2 * * *", "2026-10-30 09:00", "2026-10-30 10:15"},
		// Both days restricted: either matches, as in cron.
		{"0 12 13 * fri", "2026-10-30 18:42", "2026-11-06 12:00"},
		{"0 12 1 * 1", "2026-10-30 18:42", "2026-11-01 12:00"},
		// One of them starts with *: both must match.
		{"0 12 */2 * 1", "2026-10-30 18:42", "2026-11-09 12:00"},
		{"@hourly", "2026-10-30 18:42", "2026-10-30 19:00"},
		{"@daily", "2026-10-30 18:42", "2026-10-31 00:00"},
		{"@midnight", "2026-10-30 18:42", "2026-10-31 00:00"},
		{"@weekly", "2026-10-30 18:42", "2026-11-01 00:00"},
		{"@monthly", "2026-10-30 18:42", "2026-11-01 00:00"},
		{"@yearly", "2026-10-30 18:42", "2027-01-01 00:00"},
		{"0 0 29 2 *", "2026-10-30 18:42", "2028-02-29 00:00"},
	} {
		s, err := parseCron(c.spec)
		if err != nil {
			t.Errorf("%s: %v", c.spec, err)
			continue
		}
		if got := s.next(at(c.after, time.UTC)); !got.Equal(at(c.want, time.UTC)) {
			t.Errorf("%s after %s: %s, want %s", c.spec, c.after, got.Format("2006-01-02 15:04 Mon"), c.want)
		}
	}
	// In the VM's time zone: 3:00 in Rome is 1:00 UTC in summer, 2:00 in winter.
	s, _ := parseCron("0 3 * * *")
	if got := s.next(at("2026-07-30 18:42", time.UTC).In(rome)); !got.Equal(at("2026-07-31 03:00", rome)) || got.UTC().Hour() != 1 {
		t.Errorf("in Rome: %s (%s UTC)", got, got.UTC())
	}
	if got := s.next(at("2026-11-30 18:42", time.UTC).In(rome)); got.UTC().Hour() != 2 {
		t.Errorf("in Rome in winter: %s UTC", got.UTC())
	}
	for _, bad := range []string{"", "* * * *", "60 * * * *", "* 24 * * *", "* * 0 * *", "* * * 13 *", "* * * * 8",
		"*/0 * * * *", "5-1 * * * *", "a * * * *", "@reboot", "@often"} {
		if _, err := parseCron(bad); err == nil {
			t.Errorf("%q: no error", bad)
		}
	}
}

// What boxe-agent answers to schedule, as on a real VM: exeuntu masks most
// of Ubuntu's timers, and those it keeps (logrotate, fstrim...) must not
// count, or every VM would wake up every night.
const scheduleAnswer = `localtime /usr/share/zoneinfo/Etc/UTC
--- list-timers system
[{"next":%[1]d,"left":%[1]d,"last":0,"passed":0,"unit":"logrotate.timer","activates":"logrotate.service"},{"next":%[2]d,"left":0,"unit":"run-r1.timer","activates":"run-r1.service"},{"next":null,"left":null,"unit":"apt-daily.timer","activates":null},{"next":%[3]d,"unit":"masked.timer"}]

--- units system
Id=logrotate.timer
LoadState=loaded
FragmentPath=/usr/lib/systemd/system/logrotate.timer

Id=run-r1.timer
LoadState=loaded
FragmentPath=/run/systemd/transient/run-r1.timer

Id=apt-daily.timer
LoadState=masked
FragmentPath=/etc/systemd/system/apt-daily.timer

Id=masked.timer
LoadState=masked
FragmentPath=/etc/systemd/system/masked.timer
--- list-timers user exedev
[{"next":%[4]d,"unit":"tick.timer"},{"next":%[1]d,"unit":"launchpadlib-cache-clean.timer"}]

--- units user exedev
Id=tick.timer
LoadState=loaded
FragmentPath=/home/exedev/.config/systemd/user/tick.timer

Id=launchpadlib-cache-clean.timer
LoadState=loaded
FragmentPath=/usr/lib/systemd/user/launchpadlib-cache-clean.timer
--- crontab exedev
# DO NOT EDIT THIS FILE - edit the master and reinstall.
SHELL=/bin/bash
%[5]s
@reboot echo hi
--- cron.d mine
%[6]s
`

func answer(packaged, transient, masked, tick time.Time, crontab, cronD string) string {
	us := func(t time.Time) int64 { return t.UnixMicro() }
	return fmt.Sprintf(scheduleAnswer, us(packaged), us(transient), us(masked), us(tick), crontab, cronD)
}

func TestNextJob(t *testing.T) {
	now := time.Date(2026, 10, 30, 18, 42, 10, 0, time.UTC)
	soon, later, never := now.Add(10*time.Minute), now.Add(5*time.Hour), now.Add(-time.Hour)
	for _, c := range []struct {
		name      string
		answer    string
		want      time.Time
		wantWhat  string
		wantFound bool
	}{
		{"packaged timers do not count", answer(soon, never, soon, never, "", ""), time.Time{}, "", false},
		{"a timer started with systemd-run", answer(soon, later, soon, never, "", ""), later, "timer run-r1.timer", true},
		{"a user's timer", answer(soon, later, soon, now.Add(2*time.Hour), "", ""), now.Add(2 * time.Hour), "timer tick.timer of exedev", true},
		{"a user's crontab", answer(soon, later, soon, never, "0 19 * * * /home/exedev/backup.sh", ""),
			time.Date(2026, 10, 30, 19, 0, 0, 0, time.UTC), "cron of exedev: 0 19 * * * /home/exedev/backup.sh", true},
		{"a file in /etc/cron.d", answer(soon, later, soon, never, "", "MAILTO=me\n50 18 * * * root /usr/local/bin/x"),
			time.Date(2026, 10, 30, 18, 50, 0, 0, time.UTC), "cron.d/mine: 50 18 * * * root /usr/local/bin/x", true},
		{"lines cron would refuse are skipped", answer(soon, later, soon, never, "61 * * * * nope\n0 * * * * ok", ""),
			time.Date(2026, 10, 30, 19, 0, 0, 0, time.UTC), "cron of exedev: 0 * * * * ok", true},
		{"an older agent", "", time.Time{}, "", false},
	} {
		got, what := nextJob(c.answer, now)
		if !got.Equal(c.want) || what != c.wantWhat {
			t.Errorf("%s: %s %q, want %s %q", c.name, got, what, c.want, c.wantWhat)
		}
	}
}

// Cron reads its schedule in the VM's time zone.
func TestNextJobInTheVMsTimeZone(t *testing.T) {
	if _, err := time.LoadLocation("America/New_York"); err != nil {
		t.Skip("no time zone data:", err)
	}
	now := time.Date(2026, 10, 30, 18, 42, 0, 0, time.UTC) // 14:42 in New York
	a := "localtime ../usr/share/zoneinfo/America/New_York\n--- crontab exedev\n0 15 * * * x\n"
	got, _ := nextJob(a, now)
	if want := time.Date(2026, 10, 30, 19, 0, 0, 0, time.UTC); !got.Equal(want) {
		t.Errorf("%s, want %s", got, want)
	}
}

func TestUserTimer(t *testing.T) {
	for path, want := range map[string]bool{
		"/etc/systemd/system/backup.timer":                     true,
		"/etc/systemd/user/sync.timer":                         true,
		"/usr/local/lib/systemd/system/app.timer":              true,
		"/run/systemd/transient/run-r1.timer":                  true,
		"/home/exedev/.config/systemd/user/tick.timer":         true,
		"/home/exedev/.local/share/systemd/user/tick.timer":    true,
		"/root/.config/systemd/user/tick.timer":                true,
		"/run/user/1000/systemd/transient/run-r2.timer":        true,
		"/usr/lib/systemd/system/logrotate.timer":              false,
		"/lib/systemd/system/fstrim.timer":                     false,
		"/usr/lib/systemd/user/launchpadlib-cache-clean.timer": false,
		"/run/systemd/generator/x.timer":                       false,
		"":                                                     false,
	} {
		if got := userTimer(path, "loaded"); got != want {
			t.Errorf("%s: %v, want %v", path, got, want)
		}
	}
	if userTimer("/etc/systemd/system/apt-daily.timer", "masked") {
		t.Error("a masked timer counts")
	}
}
